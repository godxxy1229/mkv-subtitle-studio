const KO_PATTERNS = [
  [/^Cue (\d+) has no valid SRT timestamp\.$/, '$1번째 구간에 유효한 SRT 시간 정보가 없습니다.'],
  [/^Cue (\d+) is empty\.$/, '$1번째 자막 구간의 내용이 비어 있습니다.'],
  [/^Invalid SRT timestamp: (.*)$/s, 'SRT 시간 정보가 잘못되었습니다: $1'],
  [/^Analyzing MKV structure · (\d+)%$/, 'MKV 구조 분석 중 · $1%'],
];

/** Translate a message produced by the core modules; unknown messages are shown as-is. */
export function localizeMessage(lang, message) {
  if (lang !== 'ko') return message;
  if (KO_ERRORS[message]) return KO_ERRORS[message];
  for (const [pattern, replacement] of KO_PATTERNS) if (pattern.test(message)) return message.replace(pattern, replacement);
  return message;
}
